"""Provenance labels carried by every input and printed on every output.

The rule from the brief: never present an illustrative or synthetic number as
real. Each data source and config section declares one of these labels, and the
report and results JSON list them all next to the numbers they produced.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum


class Label(str, Enum):
    REAL = "REAL"                  # observed data from a named external source
    SYNTHETIC = "SYNTHETIC"        # generated by a model in this repo
    ILLUSTRATIVE = "ILLUSTRATIVE"  # placeholder value awaiting a real decision or data


@dataclass(frozen=True)
class Provenance:
    label: Label
    source: str
    details: dict = field(default_factory=dict)

    def to_dict(self) -> dict:
        return {"label": self.label.value, "source": self.source, **self.details}
