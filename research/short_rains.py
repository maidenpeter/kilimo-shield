"""Short-rains research: Layer B WRSI and C3S OND forecast skill at two eastern Kenya candidates.

REPORT ONLY. The candidates are not pilot wards: they live in a separate research
config (research/short_rains/config/, generated from config/ plus the overlay
below), and their rainfall and temperature caches sit beside it. config/ is never
changed.

Shortlist rule: of the four towns named for the scan (Mbooni, Kitui, Mwingi,
Kyuso), take the best cell near each from the 3b eastern Kenya scan and keep the
two with the highest share of annual rain falling in October-December.

    .venv/Scripts/python research/short_rains.py fetch    # CHIRPS, NASA POWER, C3S (network)
    .venv/Scripts/python research/short_rains.py run      # price and score, writes the results JSON
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))
sys.path.insert(0, str(REPO / "research"))

from agroshield_pricing.config import load_config  # noqa: E402
from agroshield_pricing.engine import price_ward  # noqa: E402
from agroshield_pricing.pet import make_pet_source  # noqa: E402
from agroshield_pricing.rainfall import make_source  # noqa: E402

HERE = REPO / "research" / "short_rains"
RESULTS = REPO / "data" / "raw" / "research" / "short_rains_results.json"
SCAN = REPO / "docs" / "research" / "3b-results.json"
TOWNS = ["Mbooni", "Kitui", "Mwingi", "Kyuso"]
SHORTLIST = 2

# ILLUSTRATIVE agronomy for semi-arid eastern Kenya short-rains maize: an early,
# drought-escaping variety planted on the late-October / November onset. Elevation
# is approximate for the cell; soil water capacity is a placeholder for lighter soils.
SITE_DEFAULTS = {
    "Mbooni": {"elevation_m": 1600, "soil_whc_mm": 100},
    "Kitui": {"elevation_m": 1150, "soil_whc_mm": 80},
    "Mwingi": {"elevation_m": 1000, "soil_whc_mm": 80},
    "Kyuso": {"elevation_m": 800, "soil_whc_mm": 80},
}
SR_CALENDAR = {
    "planting_window": {"start": "10-11", "end": "11-30"},
    "planting_rain_from": "10-11",
    "variety": "early-maturity composite (Katumani type)",
    "lgp_days": 100,
    "planting_date": "11-01",
    "phases": [{"name": "germination", "days": 15}, {"name": "vegetative", "days": 30},
               {"name": "flowering", "days": 20}, {"name": "grain_fill", "days": 25},
               {"name": "maturity", "days": 10}],
}


def shortlist() -> list[dict]:
    scan = json.loads(SCAN.read_text())["eastern_kenya"]["by_town"]
    towns = [t for t in scan if t["near"] in TOWNS]
    ranked = sorted(towns, key=lambda t: -t["best"]["ond_share"])
    out = []
    for t in ranked[:SHORTLIST]:
        b = t["best"]
        out.append({"id": f"sr-{t['near'].lower()}", "near": t["near"], "lat": round(b["lat"], 3), "lon": round(b["lon"], 3),
                    "ond_share": b["ond_share"], "ond_mm": b["ond_mm"], "mam_mm": b["mam_mm"],
                    "ond_reliable": b["ond_reliable"], "ond_cv": b["ond_cv"],
                    # 1-degree C3S cell nearest the point
                    "c3s_cell": (int(round(b["lon"])), int(round(b["lat"])))})
    out_ranked = [{"near": t["near"], "ond_share": t["best"]["ond_share"]} for t in ranked]
    return out, out_ranked


LGP_VARIANTS = [100, 80]   # days: the main calendar, and a very early (drought-escaping) variety


def build_config(sites: list[dict], lgp_days: int = 100) -> Path:
    """Copy config/ and replace the wards with the research candidates (short rains only).
    Variants live beside the main config so they share its rainfall and temperature caches."""
    CONFIG = HERE / ("config" if lgp_days == SR_CALENDAR["lgp_days"] else f"config_lgp{lgp_days}")
    CONFIG.mkdir(parents=True, exist_ok=True)
    for f in (REPO / "config").glob("*.yaml"):
        shutil.copyfile(f, CONFIG / f.name)
    head = "# GENERATED by research/short_rains.py from config/. Research only: NOT pilot wards.\n"
    wards = [{"id": s["id"], "name": f"Research candidate near {s['near']} (short rains)", "illustrative": True,
              "centroid": {"lat": s["lat"], "lon": s["lon"]}, "extraction_box_deg": 0.10,
              **SITE_DEFAULTS[s["near"]], "soil_illustrative": True, "seasons": ["SR"],
              "notes": "Best OND-main cell near the town in the 3b scan. Not a real ward boundary."} for s in sites]
    (CONFIG / "wards.yaml").write_text(head + yaml.safe_dump({"wards": wards}, sort_keys=False), encoding="utf-8",
                                       newline="\n")
    phen = yaml.safe_load((REPO / "config" / "phenology.yaml").read_text())
    phen["wards"] = {s["id"]: {"SR": {**SR_CALENDAR, "lgp_days": lgp_days}} for s in sites}
    (CONFIG / "phenology.yaml").write_text(head + yaml.safe_dump(phen, sort_keys=False), encoding="utf-8", newline="\n")
    prod = yaml.safe_load((REPO / "config" / "product.yaml").read_text())
    prod["layer_b"].pop("advance", None)              # the advance is a Ward A long-rains experiment
    # The superseded v0 per-phase index (comparison only, not reported here) cannot resolve its
    # 10th/2nd percentile levels where a phase often gets no rain at all; widen them so the engine runs.
    for ph in prod["layer_b_v0"]["phases"].values():
        ph["trigger"], ph["exit"] = {"percentile": 35}, {"percentile": 15}
    (CONFIG / "product.yaml").write_text(head + yaml.safe_dump(prod, sort_keys=False), encoding="utf-8",
                                         newline="\n")
    pilot = yaml.safe_load((REPO / "config" / "pilot.yaml").read_text())
    pilot["pilot"].update({"county": "Makueni / Kitui (research)", "wards": [s["id"] for s in sites],
                           "default_ward": sites[0]["id"]})
    (CONFIG / "pilot.yaml").write_text(head + yaml.safe_dump(pilot, sort_keys=False), encoding="utf-8", newline="\n")
    return CONFIG


def fetch(sites: list[dict]) -> None:
    from fetch_data import fetch_c3s
    cfg = load_config(build_config(sites))
    rs, ps = make_source(cfg), make_pet_source(cfg)
    y0, y1 = cfg.rainfall.history.start_year, cfg.rainfall.history.end_year
    for wid in cfg.pilot.wards:
        ward = cfg.ward(wid)
        if not rs.is_cached(ward, y0, y1):
            rs.fetch(ward, y0, y1)
        harg = getattr(ps, "base", ps)
        if hasattr(harg, "is_cached") and not harg.is_cached(ward, y0, y1):
            harg.fetch(ward, y0, y1)
    for cell in sorted({s["c3s_cell"] for s in sites}):
        tag = f"{abs(cell[0])}E_{abs(cell[1])}{'N' if cell[1] >= 0 else 'S'}"
        if not (REPO / "data" / "raw" / "research" / f"c3s_seas51_hindcast_{tag}.csv").exists():
            fetch_c3s(cell)


def c3s_ond_skill(site: dict, rain: pd.Series) -> dict:
    from skill import corr_ci, loo_lower_tercile, scores
    lon, lat = site["c3s_cell"]
    tag = f"{abs(lon)}E_{abs(lat)}{'N' if lat >= 0 else 'S'}"
    df = pd.read_csv(REPO / "data" / "raw" / "research" / f"c3s_seas51_hindcast_{tag}.csv")
    ens = df[df["season"] == "OND"].pivot(index="year", columns="member", values="mean_mm_per_day")
    ond = rain[rain.index.month.isin([10, 11, 12])]
    obs = ond.groupby(ond.index.year).sum().reindex(ens.index)
    mean = ens.mean(axis=1)
    prob = pd.Series({y: float((ens.loc[y] < np.percentile(ens.drop(y).to_numpy().ravel(), 100 / 3)).mean())
                      for y in ens.index})
    below = loo_lower_tercile(obs)
    return {"cell": {"lon": lon, "lat": lat}, "years": [int(ens.index.min()), int(ens.index.max())],
            "correlation": corr_ci(mean.to_numpy(), obs.to_numpy()), "tercile": scores(prob, below)}


def run() -> dict:
    sites, ranked = shortlist()
    out = {"rule": f"best cell near each of {', '.join(TOWNS)} from the 3b scan; top {SHORTLIST} by OND share of annual rain",
           "ranked": ranked, "calendar": SR_CALENDAR, "lgp_variants": LGP_VARIANTS, "sites": []}
    rows = {s["id"]: {**s, "c3s_cell": list(s["c3s_cell"]), **SITE_DEFAULTS[s["near"]], "layer_b": {}} for s in sites}
    for lgp in LGP_VARIANTS:
        cfg = load_config(build_config(sites, lgp))
        rs, ps = make_source(cfg, allow_download=False), make_pet_source(cfg, allow_download=False)
        for s in sites:
            r = price_ward(cfg, s["id"], rs, ps)
            rows[s["id"]]["layer_b"][str(lgp)] = _layer_b_summary(r.seasons["SR"])
            rows[s["id"]].setdefault("c3s_ond", c3s_ond_skill(s, r.rain_daily))
    out["sites"] = list(rows.values())
    RESULTS.write_text(json.dumps(out, indent=1, default=str) + "\n", encoding="utf-8", newline="\n")
    return out


def _layer_b_summary(sr) -> dict:
    t, sm = sr.table, sr.summary
    share = t["failed_onset_share"] + t["wrsi_share"]
    out = {"seasons": int(len(t)), "main_payout_frequency": float((share > 0).mean()),
           "replanting_frequency": float(t["germination_failed"].mean()),
           "failed_onset_seasons": [int(y) for y in t.index[t["failed_onset"]]],
           "median_wrsi": float(t["wrsi"].median()),
           "payout_seasons": [{"year": int(y), "wrsi": float(t.loc[y, "wrsi"]) if pd.notna(t.loc[y, "wrsi"]) else None,
                               "share": float(share[y])} for y in t.index[share > 0]]}
    out["gross_rate"] = sm["premium"]["gross_rate"]
    out["gross_kes_per_acre"] = {str(int(p["sum_insured_kes_per_acre"])): p["gross_premium_kes"]
                                 for p in sm["premium"]["per_acre"]}
    keep = ("trigger_wrsi", "main_frequency", "return_period_years", "gross_rate", "in_target_band")
    out["trigger_sensitivity"] = [{k: x[k] for k in keep} for x in sm["trigger_sensitivity"]]
    out["whc_sensitivity"] = [{k: x[k] for k in ("whc_mm", "median_wrsi", "payout_frequency", "gross_rate")}
                              for x in sm["whc_sensitivity"]]
    out["target_band"] = sm["target"]["main"]["frequency_band"]
    return out


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "run"
    if cmd == "fetch":
        fetch(shortlist()[0])
    else:
        o = run()
        for s in o["sites"]:
            for lgp, b in s["layer_b"].items():
                print(s["id"], lgp, "days: freq", round(b["main_payout_frequency"], 2), "gross", round(b["gross_rate"], 3),
                      "median WRSI", b["median_wrsi"])
            print("  C3S OND r", round(s["c3s_ond"]["correlation"]["r"], 2), s["c3s_ond"]["tercile"].get("roc_auc"))
